const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/index.html'));
const expected = fs.readFileSync(path.join(root, 'original.sha256'), 'utf8').trim();
assert.equal(crypto.createHash('sha256').update(source).digest('hex'), expected, 'El HTML fue modificado');
const scripts = [...source.toString('utf8').matchAll(/<script[^>]*>([\s\S]*?)<\/script>/gi)];
assert.ok(scripts.length > 0);
scripts.forEach((script) => new vm.Script(script[1]));
new vm.Script(fs.readFileSync(path.join(root, 'src-tauri/src/windows-open.js'), 'utf8'));
const config = JSON.parse(fs.readFileSync(path.join(root, 'src-tauri/tauri.conf.json'), 'utf8'));
assert.equal(config.build.frontendDist, '../src');
assert.equal(config.app.withGlobalTauri, true);
assert.equal(config.app.windows[0].dragDropEnabled, false);
assert.deepEqual(config.bundle.fileAssociations.flatMap(x => x.ext).sort(), ['3mf', 'glb', 'obj', 'stl']);
for (const icon of config.bundle.icon) assert.ok(fs.statSync(path.join(root, 'src-tauri', icon)).size > 0);
assert.equal(/<(?:script|link)\b[^>]*(?:src|href)\s*=\s*["']https?:/i.test(source.toString('utf8')), false);
console.log('OK: HTML original intacto, JavaScript válido, recursos incluidos y configuración coherente.');
